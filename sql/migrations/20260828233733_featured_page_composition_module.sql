do $assign_topics_featured$
declare
  v_page_id bigint;
  v_template_id bigint;
begin
  select page.id, template.id into v_page_id, v_template_id
  from public.pages page
  join public.featured_module_templates template on template.slug = 'topics-featured'
  where page.slug = 'topics';
