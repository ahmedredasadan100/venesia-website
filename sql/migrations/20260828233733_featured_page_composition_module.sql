begin;

-- Standalone Featured owner. Placement remains in Page Composition assignments;
-- content rows remain owned and read by Public Content Read.
create table if not exists public.featured_module_templates (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  description text,
  status text not null default 'unpublished'
    constraint featured_module_templates_status_check
    check (status in ('published', 'unpublished')),
  config jsonb not null default '{}'::jsonb,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.page_featured_module_assignments (
  id bigint generated by default as identity primary key,
  page_id bigint not null references public.pages(id) on delete cascade,
  template_id bigint not null references public.featured_module_templates(id) on delete cascade,
  slot text not null,
  sort_order integer not null default 0,
  is_visible boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (page_id, template_id)
);

create index if not exists page_featured_module_assignments_page_order_idx
  on public.page_featured_module_assignments(page_id, slot, sort_order, id);
create index if not exists page_featured_module_assignments_template_idx
  on public.page_featured_module_assignments(template_id);

comment on table public.featured_module_templates is
  'Featured selection and presentation templates. Does not own Public Content data or placement.';
comment on column public.page_featured_module_assignments.slot is
  'Semantic Page Composition Region selected by this Assignment.';

alter table public.featured_module_templates enable row level security;
alter table public.page_featured_module_assignments enable row level security;
revoke all on table public.featured_module_templates from public, anon, authenticated;
revoke all on table public.page_featured_module_assignments from public, anon, authenticated;
grant select, insert, update, delete on table public.featured_module_templates to service_role;
grant select, insert, update, delete on table public.page_featured_module_assignments to service_role;
grant usage, select on sequence public.featured_module_templates_id_seq to service_role;
grant usage, select on sequence public.page_featured_module_assignments_id_seq to service_role;

create or replace view public.page_composition_assignments
with (security_invoker = true)
as
select 'content'::text as kind, id, page_id, template_id, slot, sort_order, is_visible, updated_at
from public.page_content_block_assignments
union all select 'cta', id, page_id, template_id, slot, sort_order, is_visible, updated_at
from public.page_cta_block_assignments
union all select 'cards', id, page_id, template_id, slot, sort_order, is_visible, updated_at
from public.page_cards_block_assignments
union all select 'breadcrumb', id, page_id, template_id, slot, sort_order, is_visible, updated_at
from public.page_breadcrumb_block_assignments
union all select 'feed', id, page_id, template_id, slot, sort_order, is_visible, updated_at
from public.page_feed_module_assignments
union all select 'featured', id, page_id, template_id, slot, sort_order, is_visible, updated_at
from public.page_featured_module_assignments
union all select 'media_sidebar', id, page_id, template_id, slot, sort_order, is_visible, updated_at
from public.page_media_sidebar_module_assignments
union all select 'media_hub', id, page_id, template_id, slot, sort_order, is_visible, updated_at
from public.page_media_hub_module_assignments
union all
select 'hero', assignment.id, assignment.target_id, assignment.hero_id,
       'hero', greatest(0, 1000 - assignment.priority), assignment.is_active, assignment.updated_at
from public.hero_assignments assignment
where assignment.target_type = 'page' and assignment.target_id is not null;

comment on view public.page_composition_assignments is
  'Read-only aggregate projection for the existing Page Composition assignment owners, including Featured.';
revoke all on public.page_composition_assignments from anon, authenticated;
grant select on public.page_composition_assignments to service_role;

drop trigger if exists page_composition_atomic_guard on public.page_featured_module_assignments;
create trigger page_composition_atomic_guard
before insert or update or delete on public.page_featured_module_assignments
for each row execute function public.enforce_page_composition_atomic_contract();

