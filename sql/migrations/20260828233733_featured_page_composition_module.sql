do $assert_featured_owner_closure$
begin
  if exists (
    select 1 from public.media_hub_module_templates
    where section_key = 'featured'
      and coalesce(config ->> 'placement', 'hub') <> 'listing'
  ) then
    raise exception 'Featured owner closure refused: Media Hub Featured owner remains';
  end if;
  if exists (
    select 1 from public.featured_module_templates template
    where jsonb_typeof(template.config -> 'source') <> 'object'
       or template.config #>> '{source,kind}' not in ('categories', 'media-center')
       or jsonb_typeof(template.config -> 'selection') <> 'object'
       or template.config #>> '{selection,mode}' not in ('automatic', 'manual')
       or template.config #>> '{presentation,variant}' not in (
         'hero', 'editorial', 'large-card', 'three-cards', 'carousel'
       )
       or template.config ? 'placement'
  ) then
    raise exception 'Featured owner closure refused: canonical contract drift detected';
  end if;
  if to_regprocedure('public.mutate_page_composition(bigint,text,jsonb,bigint,text)') is null
     or position(
       'page_featured_module_assignments' in pg_get_functiondef(
         'public.mutate_page_composition(bigint,text,jsonb,bigint,text)'::regprocedure
       )
     ) = 0 then
    raise exception 'Featured owner closure refused: Page Composition owner adoption missing';
  end if;
  if (
    select count(*) from pg_trigger
    where tgname = 'page_composition_atomic_guard' and not tgisinternal
  ) <> 9 then
    raise exception 'Featured owner closure refused: atomic guard adoption incomplete';
  end if;
end;
$assert_featured_owner_closure$;

