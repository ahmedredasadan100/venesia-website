-- Extend the existing atomic aggregate owner in-place. The assertions make
-- this fail closed if its canonical body has drifted before this migration.
do $extend_page_composition_owner$
declare
  v_definition text;
  v_previous text;
begin
  select pg_get_functiondef(
    'public.mutate_page_composition(bigint,text,jsonb,bigint,text)'::regprocedure
  ) into v_definition;
  if v_definition is null then
    raise exception 'Featured migration refused: mutate_page_composition owner is missing';
  end if;
  if v_definition like '%page_featured_module_assignments%' then
    raise exception 'Featured migration refused: mutate_page_composition already contains Featured';
  end if;

  v_previous := v_definition;
  v_definition := replace(
    v_definition,
    'perform 1 from public.page_feed_module_assignments where page_id = p_page_id order by id for update;',
    'perform 1 from public.page_feed_module_assignments where page_id = p_page_id order by id for update;
  perform 1 from public.page_featured_module_assignments where page_id = p_page_id order by id for update;'
  );
  if v_definition = v_previous then
    raise exception 'Featured migration refused: assignment-lock owner marker drifted';
  end if;

  v_previous := v_definition;
  v_definition := replace(
    v_definition,
    'when ''feed'' then ''page_feed_module_assignments''',
    'when ''feed'' then ''page_feed_module_assignments''
      when ''featured'' then ''page_featured_module_assignments'''
  );
  if v_definition = v_previous then
    raise exception 'Featured migration refused: assignment-table owner marker drifted';
  end if;

  v_previous := v_definition;
  v_definition := replace(
    v_definition,
    'when ''feed'' then ''feed_module_templates''',
    'when ''feed'' then ''feed_module_templates''
      when ''featured'' then ''featured_module_templates'''
  );
  if v_definition = v_previous then
    raise exception 'Featured migration refused: template-table owner marker drifted';
  end if;

  v_previous := v_definition;
  v_definition := replace(
    v_definition,
    '(''page_feed_module_assignments''), (''page_media_sidebar_module_assignments''),',
    '(''page_feed_module_assignments''), (''page_featured_module_assignments''),
      (''page_media_sidebar_module_assignments''),'
  );
  if v_definition = v_previous then
    raise exception 'Featured migration refused: duplicate-page owner marker drifted';
  end if;

  execute v_definition;
end;
$extend_page_composition_owner$;

-- Adopt every non-listing Media Featured template into the new owner. Listing
-- presentation templates stay in Media Hub and never become Featured owners.
insert into public.featured_module_templates (
  name, slug, description, status, config, sort_order, created_at, updated_at
)
select
  template.name,
  template.slug,
  template.description,
  template.status,
  jsonb_build_object(
    'source', jsonb_build_object(
      'kind', 'media-center',
      'contentType', case template.config ->> 'type'
        when 'site-update' then 'site_update'
        when 'site_update' then 'site_update'
        when 'news' then 'news'
        when 'press' then 'press'
        when 'video' then 'video'
        when 'gallery' then 'gallery'
        else 'news' end
    ),
    'selection', jsonb_build_object('mode', 'automatic'),
    'itemLimit', greatest(1, least(12, coalesce(
      nullif(template.config ->> 'itemLimit', '')::integer,
      nullif(template.config ->> 'limit', '')::integer,
      1
    ))),
    'presentation', jsonb_build_object(
      'variant', 'hero',
      'eyebrow', nullif(template.config #>> '{presentation,eyebrow}', ''),
      'title', coalesce(template.config #>> '{presentation,title}', ''),
      'description', coalesce(template.config #>> '{presentation,description}', ''),
      'ctaText', coalesce(template.config #>> '{presentation,ctaText}', ''),
      'showExcerpt', true,
      'showDate', true,
      'showEyebrow', true,
      'eyebrowBold', false,
      'eyebrowAlignment', 'right',
      'showTitle', true,
      'titleBold', true,
      'titleAlignment', 'right'
    )
  ),
  template.sort_order,
  template.created_at,
  template.updated_at
from public.media_hub_module_templates template
where template.section_key = 'featured'
  and coalesce(template.config ->> 'placement', 'hub') <> 'listing'
on conflict (slug) do update set
  name = excluded.name,
  description = excluded.description,
  status = excluded.status,
  config = excluded.config,
  sort_order = excluded.sort_order,
  updated_at = excluded.updated_at;

do $adopt_featured_assignments$
begin
  perform set_config('app.page_composition_write', 'on', true);

  insert into public.page_featured_module_assignments (
    page_id, template_id, slot, sort_order, is_visible, created_at, updated_at
  )
  select
    assignment.page_id,
    featured.id,
    assignment.slot,
    assignment.sort_order,
    assignment.is_visible,
    assignment.created_at,
    assignment.updated_at
  from public.page_media_hub_module_assignments assignment
  join public.media_hub_module_templates legacy on legacy.id = assignment.template_id
  join public.featured_module_templates featured on featured.slug = legacy.slug
  where legacy.section_key = 'featured'
    and coalesce(legacy.config ->> 'placement', 'hub') <> 'listing'
  on conflict (page_id, template_id) do update set
    slot = excluded.slot,
    sort_order = excluded.sort_order,
    is_visible = excluded.is_visible,
    updated_at = excluded.updated_at;

  delete from public.page_media_hub_module_assignments assignment
  using public.media_hub_module_templates legacy
  where legacy.id = assignment.template_id
    and legacy.section_key = 'featured'
    and coalesce(legacy.config ->> 'placement', 'hub') <> 'listing';

  delete from public.media_hub_module_templates
  where section_key = 'featured'
    and coalesce(config ->> 'placement', 'hub') <> 'listing';
end;
$adopt_featured_assignments$;

