create or replace function public.mutate_project_tracking_stage(
  p_project_id bigint,
  p_actor_id bigint,
  p_action text,
  p_stage_id bigint default null,
  p_payload jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, pg_temp
as $function$
declare
  v_action text := pg_catalog.lower(pg_catalog.btrim(coalesce(p_action, '')));
  v_payload jsonb := coalesce(p_payload, '{}'::jsonb);
  v_stage public.project_tracking_stages%rowtype;
  v_sort_order integer;
  v_child_count bigint;
begin
  if p_project_id is null or p_project_id <= 0 or p_actor_id is null or p_actor_id <= 0 then
    raise exception using errcode = '22023', message = 'Valid Project and actor ids are required.';
  end if;
  if v_action not in ('create', 'update', 'delete') or pg_catalog.jsonb_typeof(v_payload) <> 'object' then
    raise exception using errcode = '22023', message = 'Tracking Stage command is invalid.';
  end if;
  if not exists (select 1 from public.projects where id = p_project_id) then
    raise exception using errcode = 'P0002', message = 'Project not found.';
  end if;
  if not exists (select 1 from public.admin_users where id = p_actor_id and is_active) then
    raise exception using errcode = '42501', message = 'Active Admin actor not found.';
  end if;

  if v_action = 'create' then
    if p_stage_id is not null or exists (
      select 1 from pg_catalog.jsonb_object_keys(v_payload) key
      where key not in (
        'name', 'description', 'start_date', 'planned_duration_value',
        'planned_duration_unit', 'is_visible'
      )
    ) then
      raise exception using errcode = '22023', message = 'Tracking Stage create payload is invalid.';
    end if;
    select coalesce(max(sort_order) + 1, 0) into v_sort_order
      from public.project_tracking_stages where project_id = p_project_id;
    insert into public.project_tracking_stages (
      project_id, name, description, sort_order, start_date,
      planned_duration_value, planned_duration_unit, is_visible, created_by, updated_by
    ) values (
      p_project_id,
      pg_catalog.btrim(v_payload ->> 'name'),
      nullif(pg_catalog.btrim(v_payload ->> 'description'), ''),
      v_sort_order,
      nullif(v_payload ->> 'start_date', '')::date,
      nullif(v_payload ->> 'planned_duration_value', '')::integer,
      nullif(pg_catalog.lower(pg_catalog.btrim(v_payload ->> 'planned_duration_unit')), ''),
      coalesce(nullif(v_payload ->> 'is_visible', '')::boolean, true),
      p_actor_id,
      p_actor_id
    ) returning * into v_stage;
  else
    if p_stage_id is null or p_stage_id <= 0 then
      raise exception using errcode = '22023', message = 'A valid Tracking Stage id is required.';
    end if;
    select * into v_stage from public.project_tracking_stages
     where id = p_stage_id and project_id = p_project_id for update;
    if not found then
      raise exception using errcode = 'P0002', message = 'Tracking Stage not found in this Project.';
    end if;
    if v_action = 'delete' then
      if v_payload <> '{}'::jsonb then
        raise exception using errcode = '22023', message = 'Tracking Stage delete accepts no payload.';
      end if;
      select count(*) into v_child_count from public.project_tracking_items where stage_id = p_stage_id;
      if v_child_count > 0 then
        raise exception using errcode = '23503', message = 'A Tracking Stage with Items cannot be deleted.';
      end if;
      delete from public.project_tracking_stages where id = p_stage_id returning * into v_stage;
    else
      if exists (
        select 1 from pg_catalog.jsonb_object_keys(v_payload) key
        where key not in (
          'name', 'description', 'start_date', 'planned_duration_value',
          'planned_duration_unit', 'is_visible'
        )
      ) then
        raise exception using errcode = '22023', message = 'Tracking Stage update payload is invalid.';
      end if;
      update public.project_tracking_stages set
        name = pg_catalog.btrim(v_payload ->> 'name'),
        description = nullif(pg_catalog.btrim(v_payload ->> 'description'), ''),
        start_date = nullif(v_payload ->> 'start_date', '')::date,
        planned_duration_value = nullif(v_payload ->> 'planned_duration_value', '')::integer,
        planned_duration_unit = nullif(pg_catalog.lower(pg_catalog.btrim(v_payload ->> 'planned_duration_unit')), ''),
        is_visible = coalesce(nullif(v_payload ->> 'is_visible', '')::boolean, false),
        updated_by = p_actor_id
      where id = p_stage_id returning * into v_stage;
    end if;
  end if;

  select count(*) into v_child_count from public.project_tracking_items where stage_id = v_stage.id;
  return pg_catalog.to_jsonb(v_stage) || pg_catalog.jsonb_build_object('item_count', v_child_count);
end
$function$;

create or replace function public.reorder_project_tracking_stages(
  p_project_id bigint,
  p_actor_id bigint,
  p_stage_ids bigint[]
)
returns integer
language plpgsql
security definer
set search_path = pg_catalog, pg_temp
as $function$
declare
  v_expected integer;
begin
  if p_project_id is null or p_project_id <= 0 or p_actor_id is null or p_actor_id <= 0 or p_stage_ids is null then
    raise exception using errcode = '22023', message = 'Tracking Stage reorder input is invalid.';
  end if;
  if not exists (select 1 from public.admin_users where id = p_actor_id and is_active) then
    raise exception using errcode = '42501', message = 'Active Admin actor not found.';
  end if;
  perform 1 from public.project_tracking_stages where project_id = p_project_id for update;
  select count(*)::integer into v_expected from public.project_tracking_stages where project_id = p_project_id;
  if pg_catalog.cardinality(p_stage_ids) <> v_expected
     or (select count(distinct ordered_id.id) from unnest(p_stage_ids) ordered_id(id)) <> v_expected
     or exists (
       select 1 from unnest(p_stage_ids) ordered_id(id)
       left join public.project_tracking_stages stage
         on stage.id = ordered_id.id and stage.project_id = p_project_id
       where stage.id is null
     ) then
    raise exception using errcode = '23514', message = 'Tracking Stage reorder must contain the exact Project Stage set.';
  end if;
  set constraints public.project_tracking_stages_project_order_key deferred;
  update public.project_tracking_stages stage set
    sort_order = ordered.ordinality - 1,
    updated_by = p_actor_id
  from unnest(p_stage_ids) with ordinality ordered(id, ordinality)
  where stage.id = ordered.id and stage.project_id = p_project_id;
  return v_expected;
end
$function$;

create or replace function public.mutate_project_tracking_item(
  p_project_id bigint,
  p_stage_id bigint,
  p_actor_id bigint,
  p_action text,
  p_item_id bigint default null,
  p_payload jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, pg_temp
as $function$
declare
  v_action text := pg_catalog.lower(pg_catalog.btrim(coalesce(p_action, '')));
  v_payload jsonb := coalesce(p_payload, '{}'::jsonb);
  v_item public.project_tracking_items%rowtype;
  v_sort_order integer;
  v_update_count bigint;
begin
  if p_project_id is null or p_project_id <= 0 or p_stage_id is null or p_stage_id <= 0
     or p_actor_id is null or p_actor_id <= 0 then
    raise exception using errcode = '22023', message = 'Valid Project, Stage and actor ids are required.';
  end if;
  if v_action not in ('create', 'update', 'delete') or pg_catalog.jsonb_typeof(v_payload) <> 'object' then
    raise exception using errcode = '22023', message = 'Tracking Item command is invalid.';
  end if;
  if not exists (
    select 1 from public.project_tracking_stages where id = p_stage_id and project_id = p_project_id
  ) then
    raise exception using errcode = '23503', message = 'Tracking Stage does not belong to this Project.';
  end if;
  if not exists (select 1 from public.admin_users where id = p_actor_id and is_active) then
    raise exception using errcode = '42501', message = 'Active Admin actor not found.';
  end if;

  if v_action = 'create' then
    if p_item_id is not null or exists (
      select 1 from pg_catalog.jsonb_object_keys(v_payload) key
      where key not in ('name', 'description', 'status', 'start_date', 'completion_date', 'is_visible')
    ) then
      raise exception using errcode = '22023', message = 'Tracking Item create payload is invalid.';
    end if;
    select coalesce(max(sort_order) + 1, 0) into v_sort_order
      from public.project_tracking_items where stage_id = p_stage_id;
    insert into public.project_tracking_items (
      stage_id, name, description, sort_order, status, start_date,
      completion_date, is_visible, created_by, updated_by
    ) values (
      p_stage_id,
      pg_catalog.btrim(v_payload ->> 'name'),
      nullif(pg_catalog.btrim(v_payload ->> 'description'), ''),
      v_sort_order,
      coalesce(nullif(pg_catalog.lower(pg_catalog.btrim(v_payload ->> 'status')), ''), 'not_started'),
      nullif(v_payload ->> 'start_date', '')::date,
      nullif(v_payload ->> 'completion_date', '')::date,
      coalesce(nullif(v_payload ->> 'is_visible', '')::boolean, true),
      p_actor_id,
      p_actor_id
    ) returning * into v_item;
  else
    if p_item_id is null or p_item_id <= 0 then
      raise exception using errcode = '22023', message = 'A valid Tracking Item id is required.';
    end if;
    select item.* into v_item
      from public.project_tracking_items item
      join public.project_tracking_stages stage on stage.id = item.stage_id
     where item.id = p_item_id and item.stage_id = p_stage_id and stage.project_id = p_project_id
     for update of item;
    if not found then
      raise exception using errcode = 'P0002', message = 'Tracking Item not found in this Stage and Project.';
    end if;
    if v_action = 'delete' then
      if v_payload <> '{}'::jsonb then
        raise exception using errcode = '22023', message = 'Tracking Item delete accepts no payload.';
      end if;
      select count(*) into v_update_count from public.project_tracking_updates where item_id = p_item_id;
      if v_update_count > 0 then
        raise exception using errcode = '23503', message = 'A Tracking Item with historical Updates cannot be deleted.';
      end if;
      delete from public.project_tracking_items where id = p_item_id returning * into v_item;
    else
      if exists (
        select 1 from pg_catalog.jsonb_object_keys(v_payload) key
        where key not in ('name', 'description', 'status', 'start_date', 'completion_date', 'is_visible')
      ) then
        raise exception using errcode = '22023', message = 'Tracking Item update payload is invalid.';
      end if;
      update public.project_tracking_items set
        name = pg_catalog.btrim(v_payload ->> 'name'),
        description = nullif(pg_catalog.btrim(v_payload ->> 'description'), ''),
        status = pg_catalog.lower(pg_catalog.btrim(v_payload ->> 'status')),
        start_date = nullif(v_payload ->> 'start_date', '')::date,
        completion_date = nullif(v_payload ->> 'completion_date', '')::date,
        is_visible = coalesce(nullif(v_payload ->> 'is_visible', '')::boolean, false),
        updated_by = p_actor_id
      where id = p_item_id returning * into v_item;
    end if;
  end if;

  select count(*) into v_update_count from public.project_tracking_updates where item_id = v_item.id;
  return pg_catalog.to_jsonb(v_item) || pg_catalog.jsonb_build_object('update_count', v_update_count);
end
$function$;

