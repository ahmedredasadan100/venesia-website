-- Project Construction Tracking Detail
--
-- Additive Tracking sub-domain. public.projects remains the sole Project
-- identity/publication/location owner. No Production rows are seeded or
-- backfilled by this migration.

begin;

create table public.project_tracking_profiles (
  project_id bigint primary key references public.projects(id) on delete restrict,
  project_receipt_date date,
  license_receipt_date date,
  contractor_name text,
  created_by bigint references public.admin_users(id) on delete set null,
  updated_by bigint references public.admin_users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint project_tracking_profiles_contractor_check
    check (contractor_name is null or btrim(contractor_name) <> '')
);

create table public.project_tracking_stages (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete restrict,
  name text not null,
  description text,
  sort_order integer not null,
  start_date date,
  planned_duration_value integer,
  planned_duration_unit text,
  is_visible boolean not null default true,
  created_by bigint references public.admin_users(id) on delete set null,
  updated_by bigint references public.admin_users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint project_tracking_stages_name_check check (btrim(name) <> ''),
  constraint project_tracking_stages_description_check check (description is null or btrim(description) <> ''),
  constraint project_tracking_stages_sort_order_check check (sort_order >= 0),
  constraint project_tracking_stages_duration_check check (
    (planned_duration_value is null and planned_duration_unit is null)
    or (planned_duration_value > 0 and planned_duration_unit in ('day', 'week', 'month'))
  ),
  constraint project_tracking_stages_project_order_key
    unique (project_id, sort_order) deferrable initially immediate
);

create table public.project_tracking_items (
  id bigint generated by default as identity primary key,
  stage_id bigint not null references public.project_tracking_stages(id) on delete restrict,
  name text not null,
  description text,
  sort_order integer not null,
  status text not null default 'not_started',
  start_date date,
  completion_date date,
  is_visible boolean not null default true,
  created_by bigint references public.admin_users(id) on delete set null,
  updated_by bigint references public.admin_users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint project_tracking_items_name_check check (btrim(name) <> ''),
  constraint project_tracking_items_description_check check (description is null or btrim(description) <> ''),
  constraint project_tracking_items_sort_order_check check (sort_order >= 0),
  constraint project_tracking_items_status_check check (status in ('not_started', 'in_progress', 'completed')),
  constraint project_tracking_items_completion_check check (
    (status = 'completed' and completion_date is not null)
    or (status <> 'completed' and completion_date is null)
  ),
  constraint project_tracking_items_date_order_check check (
    start_date is null or completion_date is null or completion_date >= start_date
  ),
  constraint project_tracking_items_stage_order_key
    unique (stage_id, sort_order) deferrable initially immediate
);

create table public.project_tracking_updates (
  id bigint generated by default as identity primary key,
  item_id bigint not null references public.project_tracking_items(id) on delete restrict,
  occurred_at timestamptz not null,
  title text not null,
  body text not null,
  publication_status text not null default 'draft',
  published_at timestamptz,
  published_by bigint references public.admin_users(id) on delete set null,
  created_by bigint references public.admin_users(id) on delete set null,
  updated_by bigint references public.admin_users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint project_tracking_updates_title_check check (btrim(title) <> ''),
  constraint project_tracking_updates_body_check check (btrim(body) <> ''),
  constraint project_tracking_updates_publication_check
    check (publication_status in ('draft', 'published', 'unpublished', 'archived')),
  constraint project_tracking_updates_published_at_check
    check (publication_status <> 'published' or published_at is not null)
);

create table public.project_tracking_update_media (
  id bigint generated by default as identity primary key,
  client_key uuid not null default gen_random_uuid(),
  update_id bigint not null references public.project_tracking_updates(id) on delete cascade,
  media_kind text not null,
  public_url text not null,
  poster_url text,
  title text,
  sort_order integer not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint project_tracking_update_media_kind_check check (media_kind in ('image', 'video')),
  constraint project_tracking_update_media_public_url_check check (btrim(public_url) <> ''),
  constraint project_tracking_update_media_poster_url_check check (poster_url is null or btrim(poster_url) <> ''),
  constraint project_tracking_update_media_title_check check (title is null or btrim(title) <> ''),
  constraint project_tracking_update_media_sort_order_check check (sort_order >= 0),
  constraint project_tracking_update_media_update_client_key unique (update_id, client_key),
  constraint project_tracking_update_media_update_order_key
    unique (update_id, sort_order) deferrable initially immediate
);

create index project_tracking_stages_project_visibility_order_idx
  on public.project_tracking_stages(project_id, is_visible, sort_order, id);
create index project_tracking_items_stage_visibility_order_idx
  on public.project_tracking_items(stage_id, is_visible, sort_order, id);
create index project_tracking_updates_item_publication_date_idx
  on public.project_tracking_updates(item_id, publication_status, occurred_at desc, id desc);
create index project_tracking_update_media_update_kind_order_idx
  on public.project_tracking_update_media(update_id, media_kind, sort_order, id);

