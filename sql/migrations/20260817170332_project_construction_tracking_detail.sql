create or replace function public.mutate_project_tracking_update(
  p_project_id bigint,
  p_item_id bigint,
  p_actor_id bigint,
  p_action text,
  p_update_id bigint default null,
  p_payload jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, pg_temp
as $function$
declare
  v_action text := pg_catalog.lower(pg_catalog.btrim(coalesce(p_action, '')));
  v_payload jsonb := coalesce(p_payload, '{}'::jsonb);
  v_update public.project_tracking_updates%rowtype;
  v_media jsonb;
  v_entry jsonb;
  v_publication_status text;
begin
  if p_project_id is null or p_project_id <= 0 or p_item_id is null or p_item_id <= 0
     or p_actor_id is null or p_actor_id <= 0 then
    raise exception using errcode = '22023', message = 'Valid Project, Item and actor ids are required.';
  end if;
  if v_action not in ('create', 'update', 'delete') or pg_catalog.jsonb_typeof(v_payload) <> 'object' then
    raise exception using errcode = '22023', message = 'Tracking Update command is invalid.';
  end if;
  if not exists (
    select 1
      from public.project_tracking_items item
      join public.project_tracking_stages stage on stage.id = item.stage_id
     where item.id = p_item_id and stage.project_id = p_project_id
  ) then
    raise exception using errcode = '23503', message = 'Tracking Item does not belong to this Project.';
  end if;
  if not exists (select 1 from public.admin_users where id = p_actor_id and is_active) then
    raise exception using errcode = '42501', message = 'Active Admin actor not found.';
  end if;

  if v_action = 'delete' then
    if p_update_id is null or p_update_id <= 0 or v_payload <> '{}'::jsonb then
      raise exception using errcode = '22023', message = 'Tracking Update delete input is invalid.';
    end if;
    select update_row.* into v_update
      from public.project_tracking_updates update_row
     where update_row.id = p_update_id and update_row.item_id = p_item_id for update;
    if not found then
      raise exception using errcode = 'P0002', message = 'Tracking Update not found in this Item.';
    end if;
    delete from public.project_tracking_updates where id = p_update_id returning * into v_update;
    return pg_catalog.to_jsonb(v_update) || pg_catalog.jsonb_build_object('media', '[]'::jsonb);
  end if;

  if exists (
    select 1 from pg_catalog.jsonb_object_keys(v_payload) key
    where key not in ('occurred_at', 'title', 'body', 'publication_status', 'media')
  ) then
    raise exception using errcode = '22023', message = 'Tracking Update payload contains unsupported fields.';
  end if;
  v_media := coalesce(v_payload -> 'media', '[]'::jsonb);
  if pg_catalog.jsonb_typeof(v_media) <> 'array' then
    raise exception using errcode = '22023', message = 'Tracking Update media must be an array.';
  end if;
  v_publication_status := pg_catalog.lower(pg_catalog.btrim(v_payload ->> 'publication_status'));
  if v_publication_status not in ('draft', 'published', 'unpublished', 'archived') then
    raise exception using errcode = '22023', message = 'Tracking Update publication status is invalid.';
  end if;

  if v_action = 'create' then
    if p_update_id is not null then
      raise exception using errcode = '22023', message = 'A new Tracking Update cannot provide an id.';
    end if;
    insert into public.project_tracking_updates (
      item_id, occurred_at, title, body, publication_status,
      published_at, published_by, created_by, updated_by
    ) values (
      p_item_id,
      (v_payload ->> 'occurred_at')::timestamptz,
      pg_catalog.btrim(v_payload ->> 'title'),
      pg_catalog.btrim(v_payload ->> 'body'),
      v_publication_status,
      case when v_publication_status = 'published' then pg_catalog.now() else null end,
      case when v_publication_status = 'published' then p_actor_id else null end,
      p_actor_id,
      p_actor_id
    ) returning * into v_update;
  else
    if p_update_id is null or p_update_id <= 0 then
      raise exception using errcode = '22023', message = 'A valid Tracking Update id is required.';
    end if;
    select update_row.* into v_update
      from public.project_tracking_updates update_row
     where update_row.id = p_update_id and update_row.item_id = p_item_id for update;
    if not found then
      raise exception using errcode = 'P0002', message = 'Tracking Update not found in this Item.';
    end if;
    update public.project_tracking_updates set
      occurred_at = (v_payload ->> 'occurred_at')::timestamptz,
      title = pg_catalog.btrim(v_payload ->> 'title'),
      body = pg_catalog.btrim(v_payload ->> 'body'),
      publication_status = v_publication_status,
      published_at = case
        when v_publication_status = 'published' then coalesce(v_update.published_at, pg_catalog.now())
        else v_update.published_at
      end,
      published_by = case
        when v_publication_status = 'published' then coalesce(v_update.published_by, p_actor_id)
        else v_update.published_by
      end,
      updated_by = p_actor_id
    where id = p_update_id returning * into v_update;
  end if;

  set constraints public.project_tracking_update_media_update_order_key deferred;
  for v_entry in select value from pg_catalog.jsonb_array_elements(v_media)
  loop
    if pg_catalog.jsonb_typeof(v_entry) <> 'object' or exists (
      select 1 from pg_catalog.jsonb_object_keys(v_entry) key
      where key not in ('client_key', 'media_kind', 'public_url', 'poster_url', 'title', 'sort_order')
    ) then
      raise exception using errcode = '22023', message = 'Tracking Update media entry is invalid.';
    end if;
    insert into public.project_tracking_update_media (
      client_key, update_id, media_kind, public_url, poster_url, title, sort_order
    ) values (
      (v_entry ->> 'client_key')::uuid,
      v_update.id,
      pg_catalog.lower(pg_catalog.btrim(v_entry ->> 'media_kind')),
      pg_catalog.btrim(v_entry ->> 'public_url'),
      nullif(pg_catalog.btrim(v_entry ->> 'poster_url'), ''),
      nullif(pg_catalog.btrim(v_entry ->> 'title'), ''),
      (v_entry ->> 'sort_order')::integer
    )
    on conflict (update_id, client_key) do update set
      media_kind = excluded.media_kind,
      public_url = excluded.public_url,
      poster_url = excluded.poster_url,
      title = excluded.title,
      sort_order = excluded.sort_order;
  end loop;

  delete from public.project_tracking_update_media media
   where media.update_id = v_update.id
     and not exists (
       select 1 from pg_catalog.jsonb_array_elements(v_media) entry
       where (entry ->> 'client_key')::uuid = media.client_key
     );

  return pg_catalog.to_jsonb(v_update) || pg_catalog.jsonb_build_object(
    'media',
    coalesce((
      select pg_catalog.jsonb_agg(pg_catalog.to_jsonb(media) order by media.sort_order, media.id)
      from public.project_tracking_update_media media where media.update_id = v_update.id
    ), '[]'::jsonb)
  );
end
$function$;

create or replace function public.project_tracking_public_detail_v1(p_slug text)
returns jsonb
language sql
stable
security invoker
set search_path = pg_catalog, pg_temp
as $function$
with project_row as (
  select
    project.id, project.slug, project.code, project.type,
    project.arabic_name, project.english_name, project.location_label,
    project.hero_image, project.hero_image_alt
  from public.projects project
  where project.slug = pg_catalog.lower(pg_catalog.btrim(p_slug))
    and project.publication_status = 'published'
),
eligible_stages as (
  select stage.*
  from public.project_tracking_stages stage
  join project_row project on project.id = stage.project_id
  where stage.is_visible
),
eligible_items as (
  select item.*
  from public.project_tracking_items item
  join eligible_stages stage on stage.id = item.stage_id
  where item.is_visible
),
eligible_updates as (
  select update_row.*
  from public.project_tracking_updates update_row
  join eligible_items item on item.id = update_row.item_id
  where update_row.publication_status = 'published'
),
media_by_update as (
  select media.update_id,
    pg_catalog.jsonb_agg(
      pg_catalog.jsonb_build_object(
        'id', media.id, 'kind', media.media_kind, 'url', media.public_url,
        'posterUrl', media.poster_url, 'title', media.title, 'sortOrder', media.sort_order
      ) order by media.sort_order, media.id
    ) as media
  from public.project_tracking_update_media media
  join eligible_updates update_row on update_row.id = media.update_id
  group by media.update_id
),
updates_with_media as (
  select update_row.*, item.stage_id, coalesce(media.media, '[]'::jsonb) as media
  from eligible_updates update_row
  join eligible_items item on item.id = update_row.item_id
  left join media_by_update media on media.update_id = update_row.id
),
updates_by_item as (
  select update_row.item_id,
    pg_catalog.jsonb_agg(
      pg_catalog.jsonb_build_object(
        'id', update_row.id, 'itemId', update_row.item_id, 'stageId', update_row.stage_id,
        'occurredAt', update_row.occurred_at, 'title', update_row.title,
        'body', update_row.body, 'publishedAt', update_row.published_at, 'media', update_row.media
      ) order by update_row.occurred_at desc, update_row.id desc
    ) as updates
  from updates_with_media update_row
  group by update_row.item_id
),
stage_statuses as (
  select stage.*,
    case
      when count(item.id) = 0 then 'not_started'
      when bool_and(item.status = 'completed') then 'completed'
      when bool_or(item.status <> 'not_started') then 'in_progress'
      else 'not_started'
    end as derived_status
  from eligible_stages stage
  left join eligible_items item on item.stage_id = stage.id
  group by
    stage.id, stage.project_id, stage.name, stage.description, stage.sort_order,
    stage.start_date, stage.planned_duration_value, stage.planned_duration_unit,
    stage.is_visible, stage.created_by, stage.updated_by, stage.created_at, stage.updated_at
),
items_by_stage as (
  select item.stage_id,
    pg_catalog.jsonb_agg(
      pg_catalog.jsonb_build_object(
        'id', item.id, 'stageId', item.stage_id, 'name', item.name,
        'description', item.description, 'sortOrder', item.sort_order,
        'status', item.status, 'startDate', item.start_date,
        'completionDate', item.completion_date,
        'updates', coalesce(updates.updates, '[]'::jsonb)
      ) order by item.sort_order, item.id
    ) as items
  from eligible_items item
  left join updates_by_item updates on updates.item_id = item.id
  group by item.stage_id
),
stages_payload as (
  select stage.id, stage.sort_order, stage.derived_status,
    pg_catalog.jsonb_build_object(
      'id', stage.id, 'projectId', stage.project_id, 'name', stage.name,
      'description', stage.description, 'sortOrder', stage.sort_order,
      'startDate', stage.start_date,
      'plannedDuration', case
        when stage.planned_duration_value is null then null
        else pg_catalog.jsonb_build_object('value', stage.planned_duration_value, 'unit', stage.planned_duration_unit)
      end,
      'status', stage.derived_status,
      'items', coalesce(items.items, '[]'::jsonb)
    ) as stage
  from stage_statuses stage
  left join items_by_stage items on items.stage_id = stage.id
),
latest_update as (
  select * from updates_with_media order by occurred_at desc, id desc limit 1
),
fallback_stage as (
  select stage.id
  from stage_statuses stage
  order by
    case stage.derived_status when 'in_progress' then 0 when 'not_started' then 1 else 2 end,
    case when stage.derived_status = 'completed' then -stage.sort_order else stage.sort_order end,
    stage.id
  limit 1
),
derived_counts as (
  select
    (select count(*) from eligible_updates)::integer as update_count,
    (select count(*) from public.project_tracking_update_media media
      join eligible_updates update_row on update_row.id = media.update_id
      where media.media_kind = 'image')::integer as image_count,
    (select count(*) from public.project_tracking_update_media media
      join eligible_updates update_row on update_row.id = media.update_id
      where media.media_kind = 'video')::integer as video_count,
    (select count(*) from stage_statuses)::integer as stage_count,
    (select count(*) from stage_statuses where derived_status = 'completed')::integer as completed_stage_count
)
select case
  when not exists (select 1 from project_row) then null
  else pg_catalog.jsonb_build_object(
    'project', (
      select pg_catalog.jsonb_build_object(
        'id', project.id, 'slug', project.slug, 'code', project.code,
        'type', project.type, 'arabicName', project.arabic_name,
        'englishName', project.english_name, 'location', project.location_label,
        'heroImage', project.hero_image, 'heroImageAlt', project.hero_image_alt
      ) from project_row project
    ),
    'profile', (
      select case when profile.project_id is null then null else pg_catalog.jsonb_build_object(
        'projectReceiptDate', profile.project_receipt_date,
        'licenseReceiptDate', profile.license_receipt_date,
        'contractorName', profile.contractor_name
      ) end
      from project_row project
      left join public.project_tracking_profiles profile on profile.project_id = project.id
    ),
    'stages', coalesce((
      select pg_catalog.jsonb_agg(stage.stage order by stage.sort_order, stage.id) from stages_payload stage
    ), '[]'::jsonb),
    'latestUpdate', (
      select pg_catalog.jsonb_build_object(
        'id', update_row.id, 'itemId', update_row.item_id, 'stageId', update_row.stage_id,
        'occurredAt', update_row.occurred_at, 'title', update_row.title,
        'body', update_row.body, 'media', update_row.media
      ) from latest_update update_row
    ),
    'currentStageId', coalesce((select stage_id from latest_update), (select id from fallback_stage)),
    'latestVisual', coalesce(
      (
        select media.value ->> 'url'
        from latest_update update_row,
          lateral pg_catalog.jsonb_array_elements(update_row.media) media(value)
        where media.value ->> 'kind' = 'image'
        order by (media.value ->> 'sortOrder')::integer limit 1
      ),
      (
        select media.value ->> 'posterUrl'
        from latest_update update_row,
          lateral pg_catalog.jsonb_array_elements(update_row.media) media(value)
        where media.value ->> 'kind' = 'video' and coalesce(media.value ->> 'posterUrl', '') <> ''
        order by (media.value ->> 'sortOrder')::integer limit 1
      ),
      (select hero_image from project_row)
    ),
    'counts', (
      select pg_catalog.jsonb_build_object(
        'updates', counts.update_count, 'images', counts.image_count,
        'videos', counts.video_count, 'stages', counts.stage_count,
        'completedStages', counts.completed_stage_count
      ) from derived_counts counts
    )
  )
end;
$function$;

