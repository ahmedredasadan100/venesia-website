  p_project_id bigint,
  p_actor_id bigint,
  p_payload jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, pg_temp
as $function$
declare
  v_payload jsonb := coalesce(p_payload, '{}'::jsonb);
  v_profile public.project_tracking_profiles%rowtype;
begin
  if p_project_id is null or p_project_id <= 0 or p_actor_id is null or p_actor_id <= 0 then
    raise exception using errcode = '22023', message = 'Valid Project and actor ids are required.';
  end if;
  if pg_catalog.jsonb_typeof(v_payload) <> 'object'
     or exists (
       select 1 from pg_catalog.jsonb_object_keys(v_payload) key
