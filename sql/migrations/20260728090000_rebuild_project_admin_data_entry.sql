-- Fail closed before COMMIT if either a default privilege or inherited runtime
-- membership still exposes a direct mutation surface.
do $project_acl_assert$
declare
  v_table text;
  v_sequence text;
  v_role text;
begin
  foreach v_table in array array[
    'project_locations',
    'projects',
    'project_location_points',
    'project_features',
    'project_floor_plans',
    'project_floor_plan_details',
    'project_delivery_items',
    'project_media',
    'project_videos'
  ]
  loop
    if not pg_catalog.has_table_privilege(
      'service_role',
      format('public.%I', v_table),
      'SELECT'
    ) or pg_catalog.has_table_privilege(
      'service_role',
      format('public.%I', v_table),
      'INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER,MAINTAIN'
    ) then
      raise exception using
        errcode = '42501',
        message = format('Unsafe service_role table ACL remains on public.%I.', v_table);
    end if;

    foreach v_role in array array['anon', 'authenticated']
    loop
      if pg_catalog.has_table_privilege(
        v_role,
        format('public.%I', v_table),
        'SELECT,INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER,MAINTAIN'
      ) then
        raise exception using
          errcode = '42501',
          message = format('Unsafe %I table ACL remains on public.%I.', v_role, v_table);
      end if;
    end loop;
  end loop;

  if exists (
    select 1
    from pg_catalog.pg_class as relation
    join pg_catalog.pg_namespace as namespace
      on namespace.oid = relation.relnamespace
    cross join lateral pg_catalog.aclexplode(relation.relacl) as acl
    where relation.relacl is not null
      and namespace.nspname = 'public'
      and relation.relname = any (array[
        'project_locations',
        'projects',
        'project_location_points',
        'project_features',
        'project_floor_plans',
        'project_floor_plan_details',
        'project_delivery_items',
        'project_media',
        'project_videos'
      ])
      and relation.relkind in ('r', 'p')
      and acl.grantee <> relation.relowner
      and not (
        acl.grantee = 'service_role'::regrole::oid
        and acl.privilege_type = 'SELECT'
        and not acl.is_grantable
      )
  ) then
    raise exception using
      errcode = '42501',
      message = 'A non-owner direct table grant remains on the Project aggregate.';
  end if;

  if exists (
    select 1
    from pg_catalog.pg_class as relation
    join pg_catalog.pg_namespace as namespace
      on namespace.oid = relation.relnamespace
    join pg_catalog.pg_attribute as attribute
      on attribute.attrelid = relation.oid
     and attribute.attnum > 0
     and not attribute.attisdropped
    cross join lateral pg_catalog.aclexplode(attribute.attacl) as acl
    where attribute.attacl is not null
      and namespace.nspname = 'public'
      and relation.relname = any (array[
