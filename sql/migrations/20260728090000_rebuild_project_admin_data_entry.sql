  end if;

  v_governorate_id := nullif(v_root ->> 'governorate_id', '')::bigint;
  v_city_id := nullif(v_root ->> 'city_id', '')::bigint;
  v_main_area_id := nullif(v_root ->> 'main_area_id', '')::bigint;
