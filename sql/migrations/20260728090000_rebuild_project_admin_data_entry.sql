        order by item.ordinality
      ) - 1,
      v_now
    from jsonb_array_elements(p_payload -> 'videos') with ordinality item(value, ordinality)
    on conflict (project_id, client_key) do update set
      section = excluded.section,
      video_url = excluded.video_url,
      poster_image = excluded.poster_image,
      poster_alt = excluded.poster_alt,
      sort_order = excluded.sort_order,
      updated_at = excluded.updated_at;
  end if;

  if (select project.overview_media_type from public.projects project where project.id = v_project_id) = 'video'
     and (
       select count(*)
         from public.project_videos video
        where video.project_id = v_project_id
          and video.section = 'overview'
     ) <> 1 then
    raise exception using
      errcode = '23514',
      message = 'Video overview mode requires exactly one overview video.';
  end if;

  -- Surface reorder collisions inside this RPC, rather than leaving initially
  -- deferred ordering constraints to fail later at an outer transaction commit.
  set constraints
    public.project_location_points_sort_unique,
    public.project_features_sort_unique,
    public.project_floor_plans_sort_unique,
    public.project_floor_plan_details_sort_unique,
    public.project_delivery_items_sort_unique,
    public.project_media_sort_unique,
    public.project_videos_sort_unique
  immediate;

  return query
  select project.id, project.slug, project.updated_at
    from public.projects project
   where project.id = v_project_id;
end
$function$;

-- Root deletion is an explicit aggregate mutation. Child rows are removed by
-- their foreign-key cascades in the same transaction; direct table DELETE stays
-- unavailable to the runtime service role.
create or replace function public.delete_project_admin_entry(
  p_project_id bigint
)
returns table (project_type text, project_slug text)
language plpgsql
volatile
security definer
set search_path = pg_catalog, pg_temp
as $function$
declare
  v_project_type text;
  v_project_slug text;
begin
  delete from public.projects as project
   where project.id = p_project_id
  returning project.type, project.slug
       into v_project_type, v_project_slug;

  if not found then
    raise exception using errcode = 'P0002', message = 'Project not found.';
  end if;

  return query select v_project_type, v_project_slug;
end
$function$;

-- Private Admin-only aggregate. RLS stays enabled and no anon/authenticated
-- policies are created. Supabase projects can carry role-specific default
-- privileges, so remove every direct non-owner grant that materialized while
-- these objects were created. This includes column grants: a table-level REVOKE
-- does not remove privileges granted on individual columns.
do $project_acl_cleanup$
declare
  v_grant record;
begin
  for v_grant in
    select distinct
      acl.grantee,
      grantee.rolname as grantee_name,
      relation.relname
    from pg_catalog.pg_class as relation
    join pg_catalog.pg_namespace as namespace
      on namespace.oid = relation.relnamespace
    cross join lateral pg_catalog.aclexplode(relation.relacl) as acl
    left join pg_catalog.pg_roles as grantee
      on grantee.oid = acl.grantee
    where relation.relacl is not null
      and namespace.nspname = 'public'
      and relation.relname = any (array[
        'project_locations',
        'projects',
        'project_location_points',
        'project_features',
        'project_floor_plans',
        'project_floor_plan_details',
        'project_delivery_items',
        'project_media',
        'project_videos'
      ])
      and relation.relkind in ('r', 'p')
      and acl.grantee <> relation.relowner
  loop
    if v_grant.grantee = 0 then
      execute format(
        'revoke all privileges on table public.%I from public cascade',
        v_grant.relname
      );
    else
      execute format(
        'revoke all privileges on table public.%I from %I cascade',
        v_grant.relname,
        v_grant.grantee_name
      );
    end if;
  end loop;

  for v_grant in
    select distinct
      acl.grantee,
      grantee.rolname as grantee_name,
      relation.relname,
      attribute.attname
    from pg_catalog.pg_class as relation
    join pg_catalog.pg_namespace as namespace
      on namespace.oid = relation.relnamespace
    join pg_catalog.pg_attribute as attribute
      on attribute.attrelid = relation.oid
     and attribute.attnum > 0
     and not attribute.attisdropped
    cross join lateral pg_catalog.aclexplode(attribute.attacl) as acl
    left join pg_catalog.pg_roles as grantee
      on grantee.oid = acl.grantee
    where attribute.attacl is not null
      and namespace.nspname = 'public'
      and relation.relname = any (array[
        'project_locations',
        'projects',
        'project_location_points',
        'project_features',
        'project_floor_plans',
        'project_floor_plan_details',
        'project_delivery_items',
        'project_media',
        'project_videos'
      ])
      and relation.relkind in ('r', 'p')
      and acl.grantee <> relation.relowner
  loop
    if v_grant.grantee = 0 then
      execute format(
        'revoke all privileges (%I) on table public.%I from public cascade',
        v_grant.attname,
        v_grant.relname
      );
    else
      execute format(
        'revoke all privileges (%I) on table public.%I from %I cascade',
        v_grant.attname,
        v_grant.relname,
        v_grant.grantee_name
      );
    end if;
  end loop;

  for v_grant in
    select distinct
      acl.grantee,
      grantee.rolname as grantee_name,
      sequence.relname
    from pg_catalog.pg_class as sequence
    join pg_catalog.pg_namespace as namespace
      on namespace.oid = sequence.relnamespace
    cross join lateral pg_catalog.aclexplode(sequence.relacl) as acl
    left join pg_catalog.pg_roles as grantee
      on grantee.oid = acl.grantee
    where sequence.relacl is not null
      and namespace.nspname = 'public'
      and sequence.relname = any (array[
        'project_locations_id_seq',
        'projects_id_seq',
        'project_location_points_id_seq',
        'project_features_id_seq',
        'project_floor_plans_id_seq',
        'project_floor_plan_details_id_seq',
        'project_delivery_items_id_seq',
        'project_media_id_seq',
        'project_videos_id_seq'
      ])
      and sequence.relkind = 'S'
      and acl.grantee <> sequence.relowner
  loop
    if v_grant.grantee = 0 then
      execute format(
        'revoke all privileges on sequence public.%I from public cascade',
        v_grant.relname
      );
    else
      execute format(
        'revoke all privileges on sequence public.%I from %I cascade',
        v_grant.relname,
        v_grant.grantee_name
      );
    end if;
  end loop;

  for v_grant in
    select distinct
      acl.grantee,
      grantee.rolname as grantee_name,
      procedure.proname,
      pg_catalog.pg_get_function_identity_arguments(procedure.oid) as identity_arguments
    from pg_catalog.pg_proc as procedure
    join pg_catalog.pg_namespace as namespace
      on namespace.oid = procedure.pronamespace
    cross join lateral pg_catalog.aclexplode(procedure.proacl) as acl
    left join pg_catalog.pg_roles as grantee
      on grantee.oid = acl.grantee
    where procedure.proacl is not null
      and namespace.nspname = 'public'
      and procedure.oid = any (array[
        'public.save_project_admin_entry(bigint,jsonb)'::regprocedure::oid,
        'public.delete_project_admin_entry(bigint)'::regprocedure::oid,
        'public.validate_project_location_parent()'::regprocedure::oid,
        'public.prevent_project_type_change()'::regprocedure::oid,
        'public.validate_project_location_selection()'::regprocedure::oid,
        'public.prevent_project_location_reparent()'::regprocedure::oid
      ])
      and acl.grantee <> procedure.proowner
  loop
    if v_grant.grantee = 0 then
      execute format(
        'revoke all privileges on function public.%I(%s) from public cascade',
        v_grant.proname,
        v_grant.identity_arguments
      );
    else
      execute format(
        'revoke all privileges on function public.%I(%s) from %I cascade',
        v_grant.proname,
        v_grant.identity_arguments,
        v_grant.grantee_name
      );
    end if;
  end loop;
end
