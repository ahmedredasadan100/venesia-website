-- Project type and the selected geographic chain are database invariants, not
-- merely Server Action conventions. These triggers also protect migration-owner
-- maintenance DML from creating an invalid aggregate.
create or replace function public.prevent_project_type_change()
returns trigger
language plpgsql
security invoker
set search_path = pg_catalog, pg_temp
as $function$
begin
  if new.type is distinct from old.type then
    raise exception using
      errcode = '23514',
      message = 'Project type is immutable after creation.';
  end if;
  return new;
end
$function$;

