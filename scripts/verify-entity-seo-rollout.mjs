import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { PGlite } from "@electric-sql/pglite";
import { loadEntitySeoPersistenceOwner } from "./backfill-entity-seo-scores.mts";

// Actual migration SQL in an ephemeral engine. The small pre-162 schema and
// Project aggregate ports below isolate the rollout contract; the native full
// baseline rehearsal separately proves the real aggregate implementations.
const owner = loadEntitySeoPersistenceOwner();
const db = new PGlite();
const sql = (name) => readFileSync(new URL(`../sql/migrations/${name}`, import.meta.url), "utf8");
const expand = sql("20260914004050_entity_seo_persisted_score.sql");
const projects = sql("20260914004118_project_seo_persisted_score.sql");
// This test supplies tiny aggregate ports, so only the actual public wrappers
// are exercised here. The raw-catalog core patch requires the real pre-162
// baseline and is executed by verify-entity-seo-cutover-postgres.mts instead.
const corePatch = projects.match(/do \$core_insert_code\$[\s\S]*?\$core_insert_code\$;/g);
assert.equal(corePatch?.length, 1, "Native core patch must remain an explicit single block.");
const projectWrappers = projects.replace(corePatch[0], "");
const enforce = sql("20260914151556_entity_seo_score_enforcement.sql");
let checks = 0;
const check = (actual, expected, message) => { assert.deepEqual(actual, expected, message); checks++; };
const one = async (query, values = []) => (await db.query(query, values)).rows[0];
const tuple = (row) => Object.fromEntries(owner.PERSISTED_ENTITY_SEO_FIELDS.map((key) => [key, row[key]]));
const unresolved = { seo_score: null, seo_score_version: null, seo_score_input_hash: null };
const derive = (entity, row) => owner.deriveEntitySeoScore(entity === "topics" ? owner.toTopicSeoScoreInput(row) : owner.toProjectSeoScoreInput(row));
const writeTuple = async (entity, id) => {
  const row = await one(`select * from ${entity} where id=$1`, [id]);
  const score = derive(entity, row);
  await db.query(`update ${entity} set seo_score=$1, seo_score_version=$2, seo_score_input_hash=$3 where id=$4`, [score.seo_score, score.seo_score_version, score.seo_score_input_hash, id]);
  check(tuple(await one(`select * from ${entity} where id=$1`, [id])), score, `${entity} accepts the actual owner proof`);
  return score;
};
const reject = async (operation, pattern) => { await assert.rejects(operation, pattern); checks++; };

try {
  await db.exec(`
    create role anon; create role authenticated; create role service_role;
    create table topics (
      id bigint generated by default as identity primary key,
      content_type text default 'article', title text, excerpt text, slug text,
      content text, image text, image_alt text, og_image text, og_image_alt text,
      seo_title text, seo_description text, seo_keywords text[], focus_keyword text, faq jsonb,
      category_id bigint, series_id bigint, media_payload jsonb, status text default 'unpublished',
      is_featured boolean default false, is_popular boolean default false,
      published_at timestamptz, created_at timestamptz default now(), updated_at timestamptz default now(),
      created_by bigint, updated_by bigint, published_by bigint, views_count bigint default 0,
      deleted_at timestamptz, canonical_url text, robots_index boolean, robots_follow boolean,
      date_label text, show_title_on_page boolean, show_image_on_page boolean, show_excerpt_on_page boolean
    );
    create table topic_categories(id bigint primary key, name text, slug text, color_token text);
    create table topic_series(id bigint primary key, name text, slug text);
    create table admin_users(id bigint primary key, full_name text, email text);
    create table projects (
      id bigint generated by default as identity primary key, type text default 'residential',
      arabic_name text, general_description text, overview_body text, slug text,
      hero_image text, hero_image_alt text, og_image text, og_image_alt text,
      seo_title text, seo_description text, seo_keywords text[], focus_keyword text,
      location_title text, overview_title text, plans_title text, delivery_title text, gallery_title text,
      show_location_label boolean default true, show_location_tags boolean default true,
      featured boolean default false, created_at timestamptz default now(), updated_at timestamptz default now()
    );
    create function save_project_admin_entry_before_section_titles(p_project_id bigint, p_payload jsonb)
    returns table(project_id bigint, slug text, updated_at timestamptz) language plpgsql as $$
    declare saved public.projects;
    begin
      if p_project_id is null then
        insert into public.projects(arabic_name,slug) values(p_payload->'project'->>'arabic_name',p_payload->'project'->>'slug') returning * into saved;
      else
        update public.projects p set arabic_name=p_payload->'project'->>'arabic_name',slug=p_payload->'project'->>'slug'
          where p.id=p_project_id returning * into saved;
      end if;
      return query select saved.id,saved.slug,saved.updated_at;
    end $$;
    create function duplicate_project_admin_entry_before_section_titles(p_project_id bigint)
    returns table(project_id bigint,project_type text,project_slug text,featured boolean,created_at timestamptz,updated_at timestamptz)
    language plpgsql as $$ declare saved public.projects; begin
      insert into public.projects(arabic_name,slug) select arabic_name||' — نسخة',slug||'-copy' from public.projects where id=p_project_id returning * into saved;
      return query select saved.id,saved.type,saved.slug,saved.featured,saved.created_at,saved.updated_at;
    end $$;
    create function duplicate_project_admin_entry(p_project_id bigint)
    returns table(project_id bigint,project_type text,project_slug text,featured boolean,created_at timestamptz,updated_at timestamptz)
    language sql as $$ select * from duplicate_project_admin_entry_before_section_titles(p_project_id) $$;
    insert into topics(title,slug) values ('Legacy topic','legacy-topic');
    insert into projects(arabic_name,slug) values ('Legacy project','legacy-project');
  `);
  await db.exec(expand);
  await db.exec(projectWrappers);
  check(tuple(await one("select * from topics where id=1")), unresolved, "EXPAND preserves legacy row as unresolved");
  const topicScore = await writeTuple("topics", 1);
  const projectScore = await writeTuple("projects", 1);
  const beforeNonSeo = await one("select * from topics where id=1");
  await db.exec("update topics set is_featured=true,status='published',views_count=19 where id=1");
  check(tuple(await one("select * from topics where id=1")), topicScore, "Non-SEO writes preserve proof");
  check((await one("select updated_at from topics where id=1")).updated_at, beforeNonSeo.updated_at, "Tuple work does not touch editorial timestamps");

  const copy = await one("insert into topics(title,slug,seo_score,seo_score_version,seo_score_input_hash) select title||' - نسخة',slug||'-copy',seo_score,seo_score_version,seo_score_input_hash from topics where id=1 returning *");
  check(tuple(copy), unresolved, "Legacy SELECT-star-shaped duplication invalidates the copied proof");
  await db.exec("update topics set title='Legacy changed title' where id=1");
  check(tuple(await one("select * from topics where id=1")), unresolved, "Legacy edit invalidates all three fields");
  await reject(() => db.exec("update topics set seo_score=50 where id=1"), /incomplete or malformed/);
  await reject(() => db.exec("update topics set seo_score=50,seo_score_version=1,seo_score_input_hash='bad' where id=1"), /incomplete or malformed/);
  await reject(() => db.exec(`update topics set seo_score=101,seo_score_version=1,seo_score_input_hash='${"a".repeat(64)}' where id=1`), /incomplete or malformed/);
  await db.query("update topics set seo_score=50,seo_score_version=1,seo_score_input_hash=$1 where id=1", ["a".repeat(64)]);
  check(tuple(await one("select * from topics where id=1")), unresolved, "A well-shaped mismatched new proof also becomes unresolved during EXPAND");
  let metrics = (await one("select admin_content_topic_metrics(1) as result")).result;
  check([metrics.seoAverage, metrics.staleScores], [null, 2], "Metrics never expose a partial average");

  await db.query("select * from save_project_admin_entry($1,$2)", [1, JSON.stringify({ project: { arabic_name: "Legacy project", slug: "legacy-project" } })]);
  check(tuple(await one("select * from projects where id=1")), projectScore, "Legacy Project save with unchanged inputs preserves valid proof");
  await db.query("select * from save_project_admin_entry($1,$2)", [1, JSON.stringify({ project: { arabic_name: "Legacy changed project", slug: "legacy-project" } })]);
  check(tuple(await one("select * from projects where id=1")), unresolved, "Legacy Project input change invalidates proof");
  const legacyProject = await one("select * from save_project_admin_entry(null,$1)", [JSON.stringify({ project: { arabic_name: "Legacy created", slug: "legacy-created" } })]);
  check(tuple(await one("select * from projects where id=$1", [legacyProject.project_id])), unresolved, "Legacy Project create survives EXPAND");
  const legacyDuplicate = await one("select * from duplicate_project_admin_entry(1)");
  check(tuple(await one("select * from projects where id=$1", [legacyDuplicate.project_id])), unresolved, "Legacy one-argument Project duplicate survives EXPAND");
  const beforeMalformedProject = await one("select * from projects where id=1");
  await reject(() => db.query("select * from save_project_admin_entry($1,$2)", [1, JSON.stringify({ project: { ...beforeMalformedProject, arabic_name: "Must roll back", seo_score: 50 } })]), /incomplete or malformed/);
  check(await one("select * from projects where id=1"), beforeMalformedProject, "Malformed Project tuple rolls back the core input edit during EXPAND");

  await reject(() => db.exec(enforce), /ENFORCE blocked/);
  await db.exec("rollback");
  check((await one("select count(*)::int as count from pg_trigger where tgname like '%entity_seo_score_transition'")).count, 2, "Failed ENFORCE leaves both transition triggers intact");
  for (const entity of ["topics", "projects"]) {
    for (const row of (await db.query(`select id from ${entity} order by id`)).rows) await writeTuple(entity, row.id);
  }
  const wrongVersion = await one("select * from topics where id=1");
  await db.exec("update topics set seo_score_version=2 where id=1");
  metrics = (await one("select admin_content_topic_metrics(1) as result")).result;
  check([metrics.seoAverage, metrics.staleScores], [null, 1], "A stale active version is excluded from the official average");
  await db.exec("update topics set deleted_at=now() where id=1");
  metrics = (await one("select admin_content_topic_metrics(1) as result")).result;
  check([metrics.seoAverage, metrics.staleScores], [derive("topics", copy).seo_score, 1], "Trash unresolved rows stay counted without corrupting active average");
  await reject(() => db.exec(enforce), /ENFORCE blocked/);
  await db.exec("rollback");
  await db.query("update topics set seo_score_version=$1,deleted_at=null where id=1", [wrongVersion.seo_score_version]);

  await db.exec(enforce);
  check((await one("select count(*)::int as count from pg_trigger where tgname like '%entity_seo_score_write' and tgdeferrable and tginitdeferred")).count, 2, "ENFORCE installs both deferred validators");
  await reject(() => db.exec("insert into topics(title,slug) values ('Old create','old-create')"), /required before commit/);
  const beforeFailure = await one("select * from topics where id=1");
  await reject(() => db.exec("update topics set title='Old edit after enforce' where id=1"), /without a new derived score proof/);
  await reject(() => db.query("update topics set seo_score_input_hash=$1 where id=1", ["b".repeat(64)]), /does not match/);
  check(await one("select * from topics where id=1"), beforeFailure, "Strict failure rolls back source and tuple together");
  const next = { ...beforeFailure, title: "Adopted valid edit" };
  const nextScore = derive("topics", next);
  await db.query("update topics set title=$1,seo_score=$2,seo_score_version=$3,seo_score_input_hash=$4 where id=1", [next.title, nextScore.seo_score, nextScore.seo_score_version, nextScore.seo_score_input_hash]);
  check(tuple(await one("select * from topics where id=1")), nextScore, "Adopted Topics proof survives ENFORCE");
  const projectCount = (await one("select count(*)::int as count from projects")).count;
  await reject(() => db.exec("select * from duplicate_project_admin_entry(1)"), /required before commit/);
  check((await one("select count(*)::int as count from projects")).count, projectCount, "Strict legacy Project duplicate leaves no root behind");
  const project = await one("select * from projects where id=1");
  const edited = { ...project, arabic_name: "Adopted Project after enforce" };
  await db.query("select * from save_project_admin_entry($1,$2)", [1, JSON.stringify({ project: { ...edited, ...derive("projects", edited) } })]);
  check(tuple(await one("select * from projects where id=1")), derive("projects", edited), "Adopted Project wrapper binds its final proof before deferred validation");
  const sourceProject = await one("select * from projects where id=1");
  const expectedCopy = { ...sourceProject, arabic_name: `${sourceProject.arabic_name} — نسخة`, slug: `${sourceProject.slug}-copy` };
  const proof = { expected_updated_at: sourceProject.updated_at, expected_source: sourceProject,
    expected_result: expectedCopy, score: derive("projects", expectedCopy) };
  const adoptedDuplicate = await one("select * from duplicate_project_admin_entry($1,$2)", [1, JSON.stringify(proof)]);
  check(tuple(await one("select * from projects where id=$1", [adoptedDuplicate.project_id])), proof.score, "Adopted Project duplicate proves the final allocated inputs after ENFORCE");
  await reject(() => db.query("select * from save_project_admin_entry($1,$2)", [1, JSON.stringify({ project: { arabic_name: "Legacy post-enforce edit", slug: sourceProject.slug } })]), /without a new derived score proof/);
  check(await one("select * from projects where id=1"), sourceProject, "Legacy Project input edit rolls back after ENFORCE");
  console.log(`Entity SEO rollout contract passed (${checks} checks; actual SQL, isolated PGlite, aggregate test ports only).`);
} finally {
  await db.close();
}
